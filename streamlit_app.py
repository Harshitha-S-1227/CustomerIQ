# ---------------------------------------------------------------------------
# Four KPI cards — real processed-results data only, honest empty state
# otherwise (never invented numbers).
# ---------------------------------------------------------------------------

if sm.has_processed_results():
    results_df = sm.get("processed_results_df")
    n_customers = len(results_df)
    avg_clv = float(results_df["predicted_clv_brl"].mean())
    n_high_value = int((results_df["clv_tier"] == "High").sum())
    total_opportunity = float(results_df["total_opportunity_brl"].sum())

    render_kpi_row(
        [
            dict(label="Customers Analysed", value=format_number(n_customers), icon="👥", accent=THEME.primary),
            dict(label="Average CLV", value=format_currency(avg_clv), icon="💰", accent=THEME.success),
            dict(
                label="High Value Customers", value=format_number(n_high_value), icon="⭐",
                accent=THEME.purple, help_text=f"{format_pct(n_high_value / n_customers)} of cohort",
            ),
            dict(label="Revenue Opportunity", value=format_currency(total_opportunity, compact=True), icon="🚀", accent=THEME.info),
        ]
    )
else:
    render_kpi_row(
        [
            dict(label="Customers Analysed", value="—", icon="👥", accent=THEME.text_muted),
            dict(label="Average CLV", value="—", icon="💰", accent=THEME.text_muted),
            dict(label="High Value Customers", value="—", icon="⭐", accent=THEME.text_muted),
            dict(label="Revenue Opportunity", value="—", icon="🚀", accent=THEME.text_muted),
        ]
    )
    st.caption("Run Batch Prediction to populate these KPIs with real results.")

st.markdown("<div style='height:20px'></div>", unsafe_allow_html=True)

