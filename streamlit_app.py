"""
streamlit_app.py — CustomerIQ frontend entry point / home dashboard.

Responsibilities (and only these — page content lives in pages/):
  1. Configure the Streamlit page (title, icon, wide layout).
  2. Inject global theme CSS so every page shares one visual language,
     including the dark enterprise sidebar (Power BI / Azure Portal
     register) — this also restyles Streamlit's own auto-generated
     page-nav links, not just the custom content in components/sidebar.py.
  3. Initialise st.session_state via services.session_manager.
  4. Render the branded sidebar (nav links are auto-generated by
     Streamlit from the pages/ directory; we only add branding + status).
  5. Show the home experience: hero, four KPI cards, Quick Actions,
     Recent Activity, and polished module cards.

KPIs and Recent Activity are built ONLY from real session_state — see
services.session_manager's `processed_*` keys. If nothing has been
processed yet, the KPI cards show an honest empty state rather than
zeros or invented numbers; Recent Activity reflects only things that
actually happened in this session.

Run with:  streamlit run streamlit_app.py
"""

