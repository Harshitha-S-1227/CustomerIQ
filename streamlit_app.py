# Quick Actions + Recent Activity
# ---------------------------------------------------------------------------

col_actions, col_activity = st.columns([1, 1])

with col_actions:
    with st.container(border=True):
        st.markdown("**Quick Actions**")
        qa1, qa2 = st.columns(2)

        with qa1:
            st.page_link(
                "pages/3_Batch_Prediction.py",
                label="📦 Run Batch Prediction",
                width="stretch"
            )
            st.page_link(
                "pages/2_Customer_Prediction.py",
                label="👤 Predict One Customer",
                width="stretch"
            )

        with qa2:
            st.page_link(
                "pages/6_Customer_Segmentation.py",
                label="🧩 View Segments",
                width="stretch"
            )
            st.page_link(
                "pages/7_Management_Reports.py",
                label="📄 Generate Report",
                width="stretch"
            )

with col_activity:
    with st.container(border=True):
        st.markdown("**Recent Activity**")
        activity_items: list[str] = []

        if sm.has_processed_results():
            n = len(sm.get("processed_results_df"))
            src = sm.get("processed_source_filename") or "uploaded file"
            when = sm.get("processed_at_utc")
            activity_items.append(f"📁 Batch Prediction scored **{n:,}** customers from `{src}`" + (f" — {when} UTC" if when else ""))

        last_customer = sm.get("cp_last_customer_id")
        if last_customer:
            activity_items.append(f"🔮 Last single prediction: customer `{last_customer}`")

        chat_history = sm.get("chat_history") or []
        if chat_history:
            activity_items.append(f"🤖 AI Copilot conversation in progress — {len(chat_history)} message(s)")

        report_result = sm.get("report_result")
        if report_result:
            activity_items.append("📑 Global SHAP feature importance computed for Management Reports")

        if not activity_items:
            st.caption("Nothing yet this session — actions you take will show up here.")
        else:
            for item in activity_items:
                st.markdown(f"- {item}")

